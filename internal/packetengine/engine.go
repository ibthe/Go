// Package packetengine defines the platform-neutral contract between a packet
// tunnel adapter and a userspace IP stack.
package packetengine

import (
	"context"
	"errors"
	"fmt"
	"sync"
)

type Family uint8

const (
	FamilyIPv4 Family = 4
	FamilyIPv6 Family = 6
)

const (
	minMTU = 1280
	maxMTU = 65535
	outputQueueSize = 1024
)

var (
	ErrNotRunning = errors.New("packet engine is not running")
	ErrInvalidMTU = errors.New("MTU must be between 1280 and 65535")
	ErrUnsupportedFamily = errors.New("unsupported IP address family")
	ErrPacketFamilyMismatch = errors.New("packet version does not match address family")
	ErrPacketExceedsMTU = errors.New("packet exceeds configured MTU")
	ErrOutputQueueFull = errors.New("packet output queue is full")
)

type Packet struct {
	Data []byte
	Family Family
}

// Processor emits packets asynchronously because TCP responses can be
// generated after the input ProcessPacket call has returned.
type Processor interface {
	Start(mtu int, emit func(Packet) error) error
	ProcessPacket(packet []byte, family Family) error
	Stop() error
}

type Engine struct {
	mu sync.Mutex
	processMu sync.Mutex
	processor Processor
	mtu int
	running bool
	output chan Packet
	stopped chan struct{}
}

func New(processor Processor) (*Engine, error) {
	if processor == nil {
		return nil, errors.New("packet processor is required")
	}
	return &Engine{processor: processor, output: make(chan Packet, outputQueueSize)}, nil
}

func (e *Engine) Start(mtu int) error {
	e.processMu.Lock()
	defer e.processMu.Unlock()
	e.mu.Lock()
	defer e.mu.Unlock()
	if e.running {
		return nil
	}
	if mtu < minMTU || mtu > maxMTU {
		return ErrInvalidMTU
	}
	e.output = make(chan Packet, outputQueueSize)
	e.stopped = make(chan struct{})
	if err := e.processor.Start(mtu, e.emit); err != nil {
		close(e.stopped)
		return fmt.Errorf("start packet processor: %w", err)
	}
	e.mtu = mtu
	e.running = true
	return nil
}

func (e *Engine) emit(packet Packet) error {
	e.mu.Lock()
	running, mtu, stopped := e.running, e.mtu, e.stopped
	e.mu.Unlock()
	if !running {
		return ErrNotRunning
	}
	if err := validatePacket(packet.Data, packet.Family, mtu); err != nil {
		return err
	}
	copyPacket := Packet{Data: append([]byte(nil), packet.Data...), Family: packet.Family}
	select {
	case e.output <- copyPacket:
		return nil
	case <-stopped:
		return ErrNotRunning
	default:
		return ErrOutputQueueFull
	}
}

func (e *Engine) Process(packet []byte, family Family) error {
	e.processMu.Lock()
	defer e.processMu.Unlock()
	e.mu.Lock()
	if !e.running {
		e.mu.Unlock()
		return ErrNotRunning
	}
	mtu := e.mtu
	e.mu.Unlock()
	if err := validatePacket(packet, family, mtu); err != nil {
		return err
	}
	if err := e.processor.ProcessPacket(append([]byte(nil), packet...), family); err != nil {
		return fmt.Errorf("process IP packet: %w", err)
	}
	return nil
}

// ReadOutput waits for the next packet generated by the userspace stack.
func (e *Engine) ReadOutput(ctx context.Context) (Packet, error) {
	e.mu.Lock()
	running, output, stopped := e.running, e.output, e.stopped
	e.mu.Unlock()
	if !running {
		return Packet{}, ErrNotRunning
	}
	select {
	case packet := <-output:
		return packet, nil
	case <-stopped:
		return Packet{}, ErrNotRunning
	case <-ctx.Done():
		return Packet{}, ctx.Err()
	}
}

func (e *Engine) Stop() error {
	e.processMu.Lock()
	defer e.processMu.Unlock()
	e.mu.Lock()
	if !e.running {
		e.mu.Unlock()
		return nil
	}
	e.running = false
	close(e.stopped)
	e.mtu = 0
	e.mu.Unlock()

	if err := e.processor.Stop(); err != nil {
		return fmt.Errorf("stop packet processor: %w", err)
	}
	return nil
}

func validatePacket(packet []byte, family Family, mtu int) error {
	if family != FamilyIPv4 && family != FamilyIPv6 {
		return ErrUnsupportedFamily
	}
	if len(packet) == 0 {
		return errors.New("empty IP packet")
	}
	if len(packet) > mtu {
		return ErrPacketExceedsMTU
	}
	version := packet[0] >> 4
	if (family == FamilyIPv4 && version != 4) || (family == FamilyIPv6 && version != 6) {
		return ErrPacketFamilyMismatch
	}
	return nil
}
